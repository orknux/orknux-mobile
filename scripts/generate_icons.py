"""Generates OrkIcons.kt from orknux-ui's own SVG assets, so both clients draw the same icons.

    python scripts/generate_icons.py <orknux-ui>/src/assets
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ICONS = {
    "ArrowLeft": "arrow-left", "Bot": "bot", "Check": "check", "ChevronDown": "chevron-down",
    "Copy": "copy", "Cpu": "cpu", "LogOut": "log-out", "Mic": "mic", "Pencil": "pencil",
    "Plus": "plus", "Refresh": "refresh-cw", "Search": "search", "Send": "send", "Stop": "square",
    "Trash": "trash-2", "Volume": "volume-2", "Alert": "alert-triangle", "Close": "x-circle",
    "Message": "message-square", "File": "file-text", "User": "user", "Brain": "brain", "Eye": "eye",
}
NS = "{http://www.w3.org/2000/svg}"


def circle_path(el):
    cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
    return f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0"


def rect_path(el):
    x, y = float(el.get("x", 0)), float(el.get("y", 0))
    w, h = float(el.get("width")), float(el.get("height"))
    return f"M{x} {y}h{w}v{h}h{-w}Z"


def line_path(el):
    return f"M{el.get('x1')} {el.get('y1')}L{el.get('x2')} {el.get('y2')}"


def poly_path(el):
    points = re.split(r"[ ,]+", el.get("points").strip())
    pairs = [f"{points[i]} {points[i + 1]}" for i in range(0, len(points), 2)]
    return "M" + "L".join(pairs) + ("Z" if el.tag == NS + "polygon" else "")


SHAPES = {"circle": circle_path, "rect": rect_path, "line": line_path, "polyline": poly_path, "polygon": poly_path}


def paths_of(file):
    root = ET.parse(file).getroot()
    size = float(root.get("viewBox", "0 0 16 16").split()[2])
    found = []
    parents = {child: parent for parent in root.iter() for child in parent}

    def inherited(el, name):
        while el is not None:
            if el.get(name) is not None:
                return el.get(name)
            el = parents.get(el)
        return None

    # A clipPath's rectangle is a mask, not something to draw.
    hidden = {id(child) for parent in root.iter() if parent.tag in (NS + "defs", NS + "clipPath") for child in parent.iter()}
    for el in root.iter():
        if id(el) in hidden:
            continue
        name = el.tag.removeprefix(NS)
        d = el.get("d") if name == "path" else SHAPES[name](el) if name in SHAPES else None
        if d is None:
            continue
        stroke = inherited(el, "stroke")
        width = float(inherited(el, "stroke-width") or 1.5)
        filled = (inherited(el, "fill") or "none") != "none"
        found.append((" ".join(d.split()), stroke not in (None, "none"), width, filled))
    return size, found


def main():
    assets = pathlib.Path(sys.argv[1])
    out = ["package io.mszymanski.orknux.mobile.design", "",
           "import androidx.compose.ui.graphics.vector.ImageVector", "",
           "/** Generated by scripts/generate_icons.py from orknux-ui's assets; do not edit. */",
           "object OrkIcons {"]
    for name, file in ICONS.items():
        size, paths = paths_of(assets / f"{file}.svg")
        parts = ", ".join(
            f'IconPath("{d}", {str(stroke).lower()}, {width}f, {str(filled).lower()})'
            for d, stroke, width, filled in paths
        )
        out.append(f'    val {name}: ImageVector by lazy {{ orkIcon("{name}", {size}f, {parts}) }}')
    out.append("}")
    target = pathlib.Path(__file__).parent.parent / "app/src/main/java/io/mszymanski/orknux/mobile/design/OrkIcons.kt"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out) + "\n", encoding="utf-8")


main()
